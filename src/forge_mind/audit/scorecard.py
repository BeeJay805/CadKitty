"""Standing validator scorecard: audit rates -> the reward-trust markdown table.

The seeded-defect audit (ADR-0083) measures how trustworthy the validator is as a reward
signal, but its rates lived only in a gitignored ``audit_results.json`` -- the per-class
picture reached the docs only when a human transcribed it. This renders the rates as a
compact standing scorecard: written into the results dir per run, and to
``docs/VALIDATOR_SCORECARD.md`` as the current instrument reading (history stays in
``docs/TEST_LOG.md`` rows; the doc is the latest measurement, not a log).

Honesty notes carried on every render: "surfaced" is the reward-readiness measure (the
signal SAW the defect, gate OR advisory); false-PASS is passed-gate-only; stated linear
dims have NO owning check (ADR-0083 v2.2) so their surfaced % is partial clean coverage,
not a designed gate.
"""

from __future__ import annotations

from typing import Any


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def _ci(pair: Any) -> str:
    try:
        lo, hi = pair
        return f"[{100 * lo:.0f}, {100 * hi:.0f}]%"
    except Exception:
        return "n/a"


def scorecard_markdown(rates: dict[str, Any], *, stamp: str, corpus_glob: str) -> str:
    """Render the audit ``rates`` block (audit_validator._rates output) as markdown."""
    lines = [
        "# Validator scorecard — the reward-trust instrument",
        "",
        "> GENERATED by `scripts/audit_validator.py` (ADR-0083) — do not hand-edit.",
        "> This is the LATEST reading; run history lives in `docs/TEST_LOG.md`.",
        "",
        f"- audit stamp: `{stamp}`",
        f"- corpus: `{corpus_glob}`",
        f"- known-goods: {rates.get('n_known_goods')} | valid mutants: "
        f"{rates.get('n_valid_mutants')} (+{rates.get('n_invalid_mutants')} not confirmed)",
        "",
        "## Top line",
        "",
        f"- **surfaced (reward-readiness): {_pct(rates.get('surfaced_rate'))}** — the signal",
        "  SAW the defect (gate OR advisory), over classes that HAVE an owning check",
        f"- false-PASS (gate-only): {_pct(rates.get('false_pass_rate'))} "
        f"{_ci(rates.get('false_pass_wilson95'))}"
        f" | print-mode: {_pct(rates.get('print_false_pass_rate'))}",
        f"- false-FAIL on known-goods: {_pct(rates.get('false_fail_rate'))} "
        f"{_ci(rates.get('false_fail_wilson95'))}",
        "",
        "## Per class",
        "",
        "| defect class | n | surfaced | false-PASS (gate) | print false-PASS | FP Wilson 95% |",
        "|---|---|---|---|---|---|",
    ]
    per_class = rates.get("per_class") or {}
    for name in sorted(per_class, key=lambda k: -per_class[k].get("n", 0)):
        c = per_class[name]
        lines.append(
            f"| {name} | {c.get('n')} | {_pct(c.get('surfaced_rate'))} "
            f"| {_pct(c.get('fp_rate'))} | {_pct(c.get('print_fp_rate'))} "
            f"| {_ci(c.get('wilson95'))} |"
        )
    lines += [
        "",
        "## Reading it honestly",
        "",
        "- `surfaced` is what matters for using the validator as a reward: did the signal",
        "  see the defect at all. `false-PASS` counts only the hard gate.",
        "- Owning checks now exist for stated extents, sub-floor walls, and stated bore",
        "  positions (ADR-0012 E1). The residual false-PASS is by construction: MODEL-derived",
        "  numbers (not user-stated) keep only the coarse envelope gate, and non-bore stated",
        "  positions (slot/rib spacings, blade angles) have no reliable B-rep measurement.",
        "  The next lever is brief->feature mapping for those unmappable-today cases.",
        f"- escapes pinned this run: {len(rates.get('escapes_pinned') or [])}; false-fails "
        f"pinned: {len(rates.get('false_fails_pinned') or [])} (full evidence in "
        "`audit_results.json`).",
        "",
    ]
    return "\n".join(lines)

"""Phase 1 EXIT GATE.

Loads the hand-authored DSL fixture, compiles it via our compiler, and verifies
the resulting STL matches the Phase 0 hand-coded build123d output within tight
tolerances (same bbox, ±0.5% volume), is manifold/single-body, and exposes
every declared op_id through the topology index.

If this test ever goes red, Phase 1 has regressed and downstream phases will
inherit the failure.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pytest
import trimesh

from forge_mind.compiler.compile import compile_program
from forge_mind.dsl.program import PartProgram

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE = REPO_ROOT / "tests" / "fixtures" / "handwritten" / "nema17_mount_good.partdsl.json"
PHASE_0_STL = REPO_ROOT / "examples" / "handwritten_nema17.stl"


# Phase 0 ground-truth measurements (from examples/handwritten_nema17.py output).
PHASE_0_BBOX = (43.0, 50.0, 30.0)
PHASE_0_VOLUME_MM3 = 11252.89
BBOX_TOL_MM = 0.2
VOLUME_TOL_PCT = 0.5

EXPECTED_OP_IDS = {
    "motor_flange",
    "ext_flange",
    "motor_bolt_nw",
    "motor_bolt_ne",
    "motor_bolt_sw",
    "motor_bolt_se",
    "shaft_clearance",
    "ext_bolt_left",
    "ext_bolt_right",
}


@pytest.fixture(scope="module")
def compiled(tmp_path_factory: pytest.TempPathFactory):  # type: ignore[no-untyped-def]
    """Compile the fixture once per module run; reuse across tests."""
    assert FIXTURE.exists(), f"DSL fixture missing: {FIXTURE}"
    program = PartProgram.model_validate(json.loads(FIXTURE.read_text()))
    out_dir = tmp_path_factory.mktemp("phase1_exit")
    return compile_program(program, out_dir)


def test_compiled_stl_exists(compiled) -> None:  # type: ignore[no-untyped-def]
    assert compiled.stl_path.exists()
    assert compiled.stl_path.stat().st_size > 0


def test_bbox_matches_phase_0(compiled) -> None:  # type: ignore[no-untyped-def]
    size = compiled.bounding_box.size
    actual = (size.x, size.y, size.z)
    for axis_name, a, expected in zip(("X", "Y", "Z"), actual, PHASE_0_BBOX, strict=True):
        assert math.isclose(a, expected, abs_tol=BBOX_TOL_MM), (
            f"bbox {axis_name} mismatch: got {a:.3f}mm, expected {expected:.3f}mm"
        )


def test_volume_matches_phase_0(compiled) -> None:  # type: ignore[no-untyped-def]
    vol = compiled.part.volume
    err_pct = abs(vol - PHASE_0_VOLUME_MM3) / PHASE_0_VOLUME_MM3 * 100
    assert err_pct <= VOLUME_TOL_PCT, (
        f"volume off by {err_pct:.3f}% (got {vol:.2f}, expected {PHASE_0_VOLUME_MM3:.2f})"
    )


def test_mesh_is_manifold(compiled) -> None:  # type: ignore[no-untyped-def]
    mesh = trimesh.load(str(compiled.stl_path), force="mesh")
    assert isinstance(mesh, trimesh.Trimesh)
    assert mesh.is_watertight, "compiled STL is not watertight"
    assert mesh.is_volume, "compiled STL is not a valid solid"
    assert mesh.is_winding_consistent, "compiled STL has inconsistent winding"
    assert mesh.body_count == 1, f"compiled STL has {mesh.body_count} bodies, expected 1"


def test_topology_index_has_all_op_ids(compiled) -> None:  # type: ignore[no-untyped-def]
    indexed = set(compiled.topology_index.op_ids())
    missing = EXPECTED_OP_IDS - indexed
    assert not missing, f"topology index missing op_ids: {sorted(missing)}"

    # Each op must have at least one tagged face.
    for op_id in EXPECTED_OP_IDS:
        faces = compiled.topology_index.faces_for(op_id)
        assert faces, f"op_id={op_id!r} has zero tagged faces"


def test_compiled_volume_matches_handwritten_stl_volume() -> None:
    """Cross-check our compiled volume against the actual Phase 0 STL on disk.

    This catches drift between the hand-coded script and our snapshot value
    above. If the script regenerates the STL with a different volume, this
    notices.
    """
    if not PHASE_0_STL.exists():
        pytest.skip(
            "Phase 0 STL not present (generated by examples/handwritten_nema17.py); "
            "the snapshot-vs-disk drift check needs the artifact, so it is skipped on a "
            "fresh checkout / CI. The compiler-vs-snapshot tests above still run."
        )
    phase_0_mesh = trimesh.load(str(PHASE_0_STL), force="mesh")
    assert isinstance(phase_0_mesh, trimesh.Trimesh)
    # The snapshot constant must stay within tolerance of the actual file.
    err_pct = abs(phase_0_mesh.volume - PHASE_0_VOLUME_MM3) / PHASE_0_VOLUME_MM3 * 100
    assert err_pct < 0.1, (
        f"Phase 0 STL on disk drifted ({phase_0_mesh.volume:.2f} vs snapshot {PHASE_0_VOLUME_MM3:.2f}); "
        f"update PHASE_0_VOLUME_MM3."
    )
